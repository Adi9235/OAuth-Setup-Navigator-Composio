// Human spot-check (EVIDENCE_AND_VERIFICATION.md). Never fabricates results: a person fills them in.
//   npm run spot-check              -> write verification/checklist.json (5 claims per seed guide)
//   npm run spot-check -- --apply   -> record filled-in outcomes in verification_log, apply
//                                      corrections as a human-created version, write VERIFICATION.md
import { loadEnvFile } from "./load-env";
loadEnvFile();

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { z } from "zod";
import { insertVerificationLog } from "@/lib/db/claims";
import { getGuideBySlug } from "@/lib/db/guides";
import { getSourcesByUrls } from "@/lib/db/sources";
import { db } from "@/lib/db/pool";
import type { Claim, Guide } from "@/lib/guide-schema";
import { SIGNAL_TITLE } from "@/lib/format";
import { saveGuideVersion } from "@/server/agent/persist";

const SEED_SLUGS = ["github", "slack", "notion", "google-workspace-apis", "linkedin"];
const DIR = join(process.cwd(), "verification");
const CHECKLIST = join(DIR, "checklist.json");

const Row = z.object({
  app: z.string(),
  slug: z.string(),
  versionNo: z.number(),
  claimId: z.string(),
  kind: z.string(), // "signal: App review", "step 3", "approval wait"
  claim: z.string(),
  evidence: z.string(),
  sourceUrl: z.string().nullable(),
  excerpt: z.string().nullable(),
  // ---- filled in by the human reviewer ----
  outcome: z.enum(["", "confirmed", "corrected", "unverifiable"]),
  method: z.enum(["", "doc_review", "setup_attempt"]),
  correctedText: z.string(),
  note: z.string(),
});
type Row = z.infer<typeof Row>;
const Checklist = z.object({ generatedAt: z.string(), instructions: z.string(), rows: z.array(Row) });

function row(guide: Guide, slug: string, versionNo: number, kind: string, c: Claim): Row {
  return {
    app: guide.app.name, slug, versionNo, claimId: c.id, kind, claim: c.text, evidence: c.evidence,
    sourceUrl: c.sources[0]?.url ?? (c.probeId ? guide.probes.find((p) => p.id === c.probeId)?.url ?? null : null),
    excerpt: c.sources[0]?.excerpt ?? (c.evidence === "uncertain" ? c.uncertaintyNote ?? null : null),
    outcome: "", method: "", correctedText: "", note: "",
  };
}

/** Stratified sample: difficulty-driving signals, approval time, and 1–2 steps (5 per guide). */
export function sampleClaims(guide: Guide, slug: string, versionNo: number): Row[] {
  const rows: Row[] = [];
  for (const k of ["reviewRequired", "securityAssessment", "partnerOrApplication"] as const)
    rows.push(row(guide, slug, versionNo, `signal: ${SIGNAL_TITLE[k]}`, guide.signals[k]));
  const timing = guide.gotchas.find((g) => g.id.startsWith("timing"));
  if (timing) rows.push(row(guide, slug, versionNo, "approval wait", timing));
  const steps = guide.steps.filter((s) => s.phase === "create" || s.phase === "submit_review");
  for (const s of (steps.length ? steps : guide.steps).slice(0, 5 - rows.length))
    rows.push(row(guide, slug, versionNo, `step: ${s.title}`, s));
  return rows.slice(0, 5);
}

async function generate() {
  const rows: Row[] = [];
  for (const slug of SEED_SLUGS) {
    const d = await getGuideBySlug(slug);
    if (!d) {
      console.log(`skip ${slug}: no published guide`);
      continue;
    }
    rows.push(...sampleClaims(d.version.content, slug, d.version.version_no));
  }
  mkdirSync(DIR, { recursive: true });
  if (existsSync(CHECKLIST)) {
    console.log(`${CHECKLIST} already exists — not overwriting your answers. Delete it to regenerate.`);
    return;
  }
  writeFileSync(CHECKLIST, JSON.stringify({
    generatedAt: new Date().toISOString(),
    instructions:
      "For each row, check the claim against the live docs (and, where possible without paid accounts, try the real flow). " +
      "Set outcome to confirmed | corrected | unverifiable, method to doc_review | setup_attempt, put the fixed text in " +
      "correctedText when corrected, and explain in note (what you checked, why unverifiable). Then run: npm run spot-check -- --apply",
    rows,
  }, null, 2) + "\n");
  console.log(`Wrote ${rows.length} rows to ${CHECKLIST}`);
}

function renderReport(rows: Row[]): string {
  const done = rows.filter((r) => r.outcome);
  const apps = [...new Set(rows.map((r) => r.app))];
  const n = (rs: Row[], o: Row["outcome"]) => rs.filter((r) => r.outcome === o).length;
  const out = [
    "# Verification report",
    "",
    "Human spot-check of a stratified sample of claims (5 per seed guide: the difficulty-driving",
    "signals, the approval wait, and 1–2 steps). Generated by `npm run spot-check -- --apply` from",
    "`verification/checklist.json`; outcomes were entered by the developer, not the agent.",
    "",
    "## Summary",
    "",
    "| App | Checked | Confirmed | Corrected | Unverifiable |",
    "|---|---|---|---|---|",
    ...apps.map((a) => {
      const rs = done.filter((r) => r.app === a);
      return `| ${a} | ${rs.length} | ${n(rs, "confirmed")} | ${n(rs, "corrected")} | ${n(rs, "unverifiable")} |`;
    }),
    `| **Total** | **${done.length}** | **${n(done, "confirmed")}** | **${n(done, "corrected")}** | **${n(done, "unverifiable")}** |`,
    "",
    "## What I corrected",
    "",
    ...(done.some((r) => r.outcome === "corrected")
      ? done.filter((r) => r.outcome === "corrected").map((r) => `- **${r.app} — ${r.kind}:** agent said “${r.claim}” → docs say “${r.correctedText}”. ${r.note}`)
      : ["- Nothing corrected in this sample."]),
    "",
    "## What I tried hands-on",
    "",
    ...(done.some((r) => r.method === "setup_attempt")
      ? done.filter((r) => r.method === "setup_attempt").map((r) => `- **${r.app} — ${r.kind}:** ${r.outcome}. ${r.note}`)
      : ["- No hands-on setup attempts recorded yet."]),
    "",
    "## What I could not verify",
    "",
    ...(done.some((r) => r.outcome === "unverifiable")
      ? done.filter((r) => r.outcome === "unverifiable").map((r) => `- **${r.app} — ${r.kind}:** ${r.note || "no reason given"}`)
      : ["- Everything in the sample was verifiable."]),
    "",
  ];
  if (done.length < rows.length) out.push(`_${rows.length - done.length} of ${rows.length} sampled claims have not been reviewed yet._`, "");
  return out.join("\n");
}

async function apply() {
  if (!existsSync(CHECKLIST)) throw new Error("No checklist yet — run `npm run spot-check` first");
  const { rows } = Checklist.parse(JSON.parse(readFileSync(CHECKLIST, "utf8")));
  const done = rows.filter((r) => r.outcome);
  for (const r of done) {
    if (r.outcome === "corrected" && !r.correctedText.trim()) throw new Error(`Row "${r.app} — ${r.kind}" is corrected but has no correctedText`);
    if (!r.method) throw new Error(`Row "${r.app} — ${r.kind}" needs a method (doc_review or setup_attempt)`);
  }

  // Corrections become a new human-created version per guide.
  for (const slug of [...new Set(done.filter((r) => r.outcome === "corrected").map((r) => r.slug))]) {
    const d = await getGuideBySlug(slug);
    if (!d) continue;
    const guide = structuredClone(d.version.content);
    const fixes = done.filter((r) => r.slug === slug && r.outcome === "corrected");
    const walk = [...Object.values(guide.signals), ...guide.prerequisites, ...guide.steps, ...guide.scopes, ...guide.gotchas];
    for (const fix of fixes) {
      const claim = walk.find((c) => c.id === fix.claimId);
      if (claim) claim.text = fix.correctedText.trim();
    }
    const lookup = new Map((await getSourcesByUrls(guide.sources.map((s) => s.url))).map((s) => [s.url, { sourceId: s.id, snapshotId: s.latest_snapshot_id }]));
    const saved = await saveGuideVersion({
      app: d.app, guide, sources: lookup, createdBy: "human",
      changeSummary: `Human spot-check: corrected ${fixes.length} claim${fixes.length === 1 ? "" : "s"}`,
    });
    console.log(`${slug}: saved v${saved.versionNo} with ${fixes.length} correction(s)`);
  }

  // Log every reviewed claim against the claim row it was sampled from.
  let logged = 0;
  for (const r of done) {
    const claimId = r.claimId.replace(/^timing:/, "");
    if (!/^[0-9a-f-]{36}$/i.test(claimId)) continue;
    await insertVerificationLog({
      claimId, verifiedBy: "human", method: r.method as "doc_review" | "setup_attempt", outcome: r.outcome as "confirmed" | "corrected" | "unverifiable",
      originalText: r.outcome === "corrected" ? r.claim : null, correctedText: r.outcome === "corrected" ? r.correctedText : null, note: r.note || null,
    });
    logged++;
  }
  writeFileSync(join(process.cwd(), "VERIFICATION.md"), renderReport(rows));
  console.log(`Logged ${logged} human verification(s); wrote VERIFICATION.md`);
}

(process.argv.includes("--apply") ? apply() : generate())
  .catch((err: unknown) => {
    console.error(err instanceof Error ? err.message : err);
    process.exitCode = 1;
  })
  .finally(() => db().end());
